#!/usr/bin/env python3
"""Export one local AI-region run using the public-text research schema.

This is a thin region-aware wrapper around the established Guangzhou research
exporter. It canonicalizes note URLs, redacts direct PII from public text,
omits raw identity/session/proxy fields, and keeps unresolved worklist rows.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any

import export_ai_guangzhou_research_text as exporter


WORKLIST_FIELDS = [
    "event_id", "event_name", "phase_id", "phase_name", "event_type",
    "source_keyword", "region", "lane", "target_sequence", "note_id",
    "note_url_public", "representative_rank_in_phase", "representative_score",
    "selection_reason",
]
COMPLETION_FIELDS = [
    "event_id", "event_name", "phase_id", "phase_name", "region", "lane",
    "target_sequence", "note_id", "effective_status", "content_available",
    "started_at", "finished_at",
]
NOTE_FIELDS = [
    "event_id", "event_name", "phase_id", "phase_name", "event_type",
    "source_keyword", "region", "note_id", "note_url_public", "title", "desc",
    "tag_list", "publish_time_bj", "publish_date_bj", "public_ip_location",
    "liked_count_num", "collected_count_num", "comment_count_num",
    "share_count_num", "representative_score", "representative_rank_in_phase",
    "is_representative_sample", "is_marketing", "content_type", "author_id_anon",
    "text_redacted", "pii_redaction_count", "pii_types",
]
COMMENT_FIELDS = [
    "event_id", "phase_id", "note_id", "comment_id", "parent_comment_id",
    "comment_text", "comment_time_bj", "comment_date_bj", "comment_like_count",
    "commenter_region", "is_reply", "sub_comment_count",
    "note_is_representative_sample", "commenter_id_anon", "content_type",
    "text_redacted", "pii_redaction_count", "pii_types", "dangling_parent",
]
PAGINATION_FIELDS = [
    "event_id", "phase_id", "target_sequence", "note_id", "kind",
    "root_comment_id", "status", "stop_reason", "pages", "observed_comments",
    "declared_comments", "reply_target_count", "has_more", "unlimited",
    "recorded_at",
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-root", type=Path, required=True, help="Folder containing the device folder")
    parser.add_argument("--device-id", required=True)
    parser.add_argument("--lane", default="local")
    parser.add_argument("--region", required=True)
    parser.add_argument("--worklist", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--hmac-key-file", type=Path, required=True)
    parser.add_argument("--dataset-id", required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--overwrite", action="store_true", help="Refresh files generated by this exporter in the selected output directory")
    args = parser.parse_args()

    run_root = args.run_root.resolve()
    output = args.output_dir.resolve()
    if output.exists() and any(output.iterdir()) and not args.overwrite:
        raise SystemExit(f"Refusing to overwrite non-empty output directory: {output}")
    secret = args.hmac_key_file.read_bytes().strip()
    if len(secret) < 32:
        raise SystemExit("HMAC key must contain at least 32 bytes and remain outside the repository")
    if not (run_root / args.device_id / "batch_ledger.csv").is_file():
        raise SystemExit(f"No batch ledger for device {args.device_id!r} under {run_root}")

    # The source ledgers use `empty` for a completed target with no accessible
    # detail payload. Treat it as terminal without pretending that text exists.
    exporter.LANES = {args.device_id: args.lane}
    exporter.RESOLVED = {"ok", "empty", "skipped_unavailable"}
    worklist = exporter.collect_worklist(args.worklist.resolve())
    if not worklist:
        raise SystemExit("Worklist is empty")
    for row in worklist:
        row["region"] = args.region
        row["lane"] = args.lane
    if len({row["note_id"] for row in worklist}) != len(worklist):
        raise SystemExit("Worklist contains duplicate note_id values")

    work_by_note = {row["note_id"]: row for row in worklist}
    progress = exporter.collect_progress(run_root)
    notes = exporter.collect_notes(run_root, work_by_note, secret)
    note_ids = {row["note_id"] for row in notes}
    comments = exporter.collect_comments(run_root, work_by_note, note_ids, secret)
    pagination = exporter.collect_pagination(run_root, work_by_note)
    completion = exporter.make_completion(worklist, progress, note_ids)
    for row in completion:
        if row["effective_status"] == "empty":
            row["effective_status"] = "completed_without_accessible_content"

    terminal_statuses = {
        "content_collected", "structurally_complete_reuse",
        "completed_without_accessible_content",
    }
    remaining_tasks = [row for row in completion if row["effective_status"] not in terminal_statuses]

    output.mkdir(parents=True, exist_ok=True)
    data_rows = {
        "worklist.csv": (WORKLIST_FIELDS, worklist),
        "collection_completion.csv": (COMPLETION_FIELDS, completion),
        "remaining_tasks.csv": ([
            "event_id", "phase_id", "target_sequence", "note_id", "effective_status",
            "started_at", "finished_at",
        ], remaining_tasks),
        "notes_unified.csv": (NOTE_FIELDS, notes),
        "comments_unified.csv": (COMMENT_FIELDS, comments),
        "pagination_status.csv": (PAGINATION_FIELDS, pagination),
    }
    row_counts = {
        name: exporter.write_csv(output / name, fields, rows)
        for name, (fields, rows) in data_rows.items()
    }

    phase_summary = []
    for phase in sorted({row["phase_id"] for row in worklist}):
        target_rows = [row for row in worklist if row["phase_id"] == phase]
        phase_completion = [row for row in completion if row["phase_id"] == phase]
        phase_notes = [row for row in notes if row["phase_id"] == phase]
        phase_comments = [row for row in comments if row["phase_id"] == phase]
        phase_pages = [row for row in pagination if row["phase_id"] == phase]
        counts = Counter(row["effective_status"] for row in phase_completion)
        phase_summary.append({
            "phase_id": phase,
            "phase_name": target_rows[0]["phase_name"],
            "target_notes": len(target_rows),
            "content_collected": counts["content_collected"],
            "structurally_complete_reuse": counts["structurally_complete_reuse"],
            "completed_without_accessible_content": counts["completed_without_accessible_content"],
            "login_expired": counts["login_expired"],
            "missing_terminal_status": counts["missing_terminal_status"],
            "other_unresolved": sum(v for k, v in counts.items() if k not in {
                "content_collected", "structurally_complete_reuse",
                "completed_without_accessible_content", "login_expired",
                "missing_terminal_status",
            }),
            "landed_notes": len(phase_notes),
            "comments": len(phase_comments),
            "top_level_comments": sum(row["is_reply"] == "false" for row in phase_comments),
            "reply_comments": sum(row["is_reply"] == "true" for row in phase_comments),
            "pagination_records": len(phase_pages),
        })
    row_counts["event_phase_summary.csv"] = exporter.write_csv(
        output / "event_phase_summary.csv",
        ["phase_id", "phase_name", "target_notes", "content_collected",
         "structurally_complete_reuse", "completed_without_accessible_content",
         "login_expired", "missing_terminal_status", "other_unresolved",
         "landed_notes", "comments", "top_level_comments", "reply_comments",
         "pagination_records"],
        phase_summary,
    )

    statuses = Counter(row["effective_status"] for row in completion)
    pagination_statuses = Counter(row["status"] for row in pagination)
    comment_types = Counter(row["content_type"] for row in comments)
    content_without_note = sum(
        row["effective_status"] == "content_collected" and row["content_available"] != "true"
        for row in completion
    )
    content_with_note = {row["note_id"] for row in completion if row["content_available"] == "true"}
    pagination_by_note: dict[str, list[dict[str, Any]]] = {}
    for row in pagination:
        pagination_by_note.setdefault(row["note_id"], []).append(row)
    notes_without_top_page = sum(
        not any(row["kind"] == "top_level" for row in pagination_by_note.get(note_id, []))
        for note_id in content_with_note
    )
    notes_with_incomplete_pagination = sum(
        any(row["status"] != "complete" for row in pagination_by_note.get(note_id, []))
        for note_id in content_with_note
    )
    quality = {
        "region": args.region,
        "target_notes": len(worklist),
        "unique_worklist_note_ids": len(work_by_note),
        "completion_rows": len(completion),
        "terminal_status_counts": dict(sorted(statuses.items())),
        "landed_notes": len(notes),
        "content_collected_without_landed_note": content_without_note,
        "notes_with_title": sum(bool(row["title"].strip()) for row in notes),
        "notes_with_desc": sum(bool(row["desc"].strip()) for row in notes),
        "notes_with_tags": sum(bool(row["tag_list"].strip()) for row in notes),
        "note_rows_with_pii_redaction": sum(row["text_redacted"] == "true" for row in notes),
        "note_pii_fragments_redacted": sum(int(row["pii_redaction_count"]) for row in notes),
        "comments": len(comments),
        "top_level_comments": sum(row["is_reply"] == "false" for row in comments),
        "reply_comments": sum(row["is_reply"] == "true" for row in comments),
        "comments_with_text": sum(bool(row["comment_text"].strip()) for row in comments),
        "comment_content_types": dict(sorted(comment_types.items())),
        "comment_rows_with_pii_redaction": sum(row["text_redacted"] == "true" for row in comments),
        "comment_pii_fragments_redacted": sum(int(row["pii_redaction_count"]) for row in comments),
        "dangling_parent_relationships": sum(row["dangling_parent"] == "true" for row in comments),
        "pagination_records": len(pagination),
        "pagination_status_counts": dict(sorted(pagination_statuses.items())),
        "content_notes_without_top_level_pagination_record": notes_without_top_page,
        "content_notes_with_incomplete_pagination": notes_with_incomplete_pagination,
        "orphan_comment_note_ids": len({row["note_id"] for row in comments} - note_ids),
        "duplicate_note_ids": len(notes) - len({row["note_id"] for row in notes}),
        "duplicate_comment_keys": len(comments) - len({(row["note_id"], row["comment_id"]) for row in comments}),
    }
    (output / "quality_summary.json").write_text(
        json.dumps(quality, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    inventory = []
    for name in [*data_rows, "event_phase_summary.csv", "quality_summary.json"]:
        path = output / name
        inventory.append({
            "file": name,
            "rows": row_counts.get(name, 1),
            "bytes": path.stat().st_size,
            "sha256": exporter.sha256_file(path),
        })
    row_counts["data_inventory.csv"] = exporter.write_csv(
        output / "data_inventory.csv", ["file", "rows", "bytes", "sha256"], inventory
    )

    snapshot_at = datetime.now(exporter.BJ).isoformat(timespec="seconds")
    pending = len(remaining_tasks)
    manifest = {
        "schema_version": "ai-keyword-followup-research-text-v1",
        "dataset_id": args.dataset_id,
        "snapshot_at": snapshot_at,
        "run_id": args.run_id,
        "region": args.region,
        "collection_platform": "RedNote international",
        "target_notes": len(worklist),
        "content_collected_notes": statuses["content_collected"],
        "structurally_complete_reuse": statuses["structurally_complete_reuse"],
        "completed_without_accessible_content": statuses["completed_without_accessible_content"],
        "unresolved_targets": pending,
        "landed_notes": len(notes),
        "comment_rows": len(comments),
        "top_level_comment_rows": quality["top_level_comments"],
        "reply_comment_rows": quality["reply_comments"],
        "pagination_records": len(pagination),
        "privacy": {
            "included": "public post/comment text, public engagement counts, generalized public location, canonical note URLs, relationship and pagination evidence",
            "excluded": "cookies, browser/session state, signed access URLs, xsec tokens, media URLs, crawler logs, proxy/egress details, device/account identifiers, nicknames and raw author/commenter identifiers",
            "identity_method": "HMAC-SHA256; per-export key is kept outside the repository",
            "text_method": "public text retained; detected PII fragments replaced in place and counted",
        },
        "deduplication": {
            "notes": "note_id within region; latest last_modify_ts with text completeness tie-break",
            "comments": "(note_id, comment_id) within region; latest last_modify_ts with content completeness tie-break",
            "pagination": "(note_id, kind, root_comment_id); latest recorded_at",
            "progress": "(phase_id, chunk); terminal result preferred, latest finished_at tie-break",
        },
        "files": row_counts,
        "integrity": quality,
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    readme = f"""# {args.region} AI-keyword collection — research-text delivery

- Snapshot: `{snapshot_at}` (Asia/Shanghai)
- Run: `{args.run_id}`
- Frozen targets: **{len(worklist):,}**
- Public post bodies collected: **{len(notes):,}**
- Deduplicated public comments: **{len(comments):,}** = {quality['top_level_comments']:,} top-level + {quality['reply_comments']:,} replies
- Target outcomes: `{json.dumps(dict(sorted(statuses.items())), ensure_ascii=False)}`
- Content notes missing top-level pagination evidence: **{notes_without_top_page:,}**
- Content notes with incomplete latest pagination: **{notes_with_incomplete_pagination:,}**

`notes_unified.csv`, `comments_unified.csv` and `pagination_status.csv` use the same research-text schema as the existing Chengdu and Guangzhou deliveries. The worklist preserves every selected target and the completion file leaves login-expired/not-started work explicitly unresolved. `empty` ledger outcomes are represented as `completed_without_accessible_content`; they are not counted as posts with collected text.

The export contains public research text only. It excludes browser profiles, cookies, signed URLs/access tokens, media URLs, crawler logs, proxy/egress details, account/device identifiers, nicknames and raw author/commenter IDs. Textual PII patterns are redacted; author/commenter linkage is HMAC-SHA256 pseudonymized with a per-export key that is not stored in Git. `remaining_tasks.csv` contains only targets with a non-terminal ledger state; completed tasks are not included there.
"""
    (output / "README.md").write_text(readme, encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
